package Modelo;

public class Dashboard {
    private int usuarios;
    private int docentes;
    private int estudiantes;
    private int cursos;
    private int secciones;
    private int matriculas;
    private int asignaciones;
    private int anuncios;

    public int getUsuarios() { return usuarios; }
    public void setUsuarios(int usuarios) { this.usuarios = usuarios; }
    public int getDocentes() { return docentes; }
    public void setDocentes(int docentes) { this.docentes = docentes; }
    public int getEstudiantes() { return estudiantes; }
    public void setEstudiantes(int estudiantes) { this.estudiantes = estudiantes; }
    public int getCursos() { return cursos; }
    public void setCursos(int cursos) { this.cursos = cursos; }
    public int getSecciones() { return secciones; }
    public void setSecciones(int secciones) { this.secciones = secciones; }
    public int getMatriculas() { return matriculas; }
    public void setMatriculas(int matriculas) { this.matriculas = matriculas; }
    public int getAsignaciones() { return asignaciones; }
    public void setAsignaciones(int asignaciones) { this.asignaciones = asignaciones; }
    public int getAnuncios() { return anuncios; }
    public void setAnuncios(int anuncios) { this.anuncios = anuncios; }
}